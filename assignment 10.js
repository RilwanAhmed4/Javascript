//Create an empty array
//	push 10,20 and 30 into it
//	use pop to remove the last element
//	use unshift(5) to add 5 at the beginning
//	use shift to remove the first element
//	print the final array after each operation


let num=[];
num.push("10","20","30");
console.log(num); //push 10,20 and 30 into it
num.pop();
console.log(num); //	use pop to remove the last element
num.unshift(5);
console.log(num); //use unshift(5) to add 5 at the beginning
num.shift(5);
console.log(num); //use shift to remove the first element

